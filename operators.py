#Arithmetic operators
a=10
b=5
print(a+b)
print(a-b)
print(a*b)
print(a/b)
print(a%b)
print(a**b)
print(a//b)

#Logical operators
a =10
print(a>5 and a<15) #And operator
print(a>5 or a<15) #Or operator
print(not(a>5 and a<15)) #Not operator

#Comparison operators
a=20
b=10
print(a==b)
print(a!=b)
print(a>b)
print(a<b)
print(a>=b)
print(a<=b)